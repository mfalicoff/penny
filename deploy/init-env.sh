#!/bin/sh
# Writes deploy/.env for deploy/compose.yaml (MAZ-63) with random, separate admin,
# migration and runtime passwords and a random receipt master key. Mode 0600; refuses
# to overwrite an existing file (changing .env does not rotate database passwords and
# a new receipt key cannot read existing receipts).
#   sh deploy/init-env.sh https://penny.example.com
set -eu
origin="${1:-}"
case "$origin" in
  https://* | http://localhost* | http://127.0.0.1*) ;;
  *)
    echo "Usage: sh deploy/init-env.sh https://penny.example.com (the public origin users open)" >&2
    exit 2
    ;;
esac
origin="${origin%/}"
target="${PENNY_ENV_FILE:-$(cd "$(dirname "$0")" && pwd)/.env}"
if [ -e "$target" ]; then
  echo "$target already exists; not overwriting it." >&2
  exit 1
fi
secret() { od -An -tx1 -N24 /dev/urandom | tr -d ' \n'; }
secure=true
case "$origin" in http://*) secure=false ;; esac
umask 077
cat > "$target" <<EOF
# Generated by deploy/init-env.sh. Keep this file (mode 0600) and the receipt key in
# your secret manager: losing PENNY_RECEIPT_KEY makes stored receipts unreadable.
PENNY_PUBLIC_ORIGIN=$origin
PENNY_SECURE_COOKIES=$secure
COMPOSE_PROFILES=bundled-postgres
PENNY_ADMIN_PASSWORD=$(secret)
PENNY_MIGRATION_PASSWORD=$(secret)
PENNY_RUNTIME_PASSWORD=$(secret)
PENNY_RECEIPT_KEY=$(head -c 32 /dev/urandom | base64 | tr -d '\n')
# Pin released images instead of latest, e.g. ghcr.io/mfalicoff/penny-api:2.0.0
PENNY_API_IMAGE=ghcr.io/mfalicoff/penny-api:latest
PENNY_WEB_IMAGE=ghcr.io/mfalicoff/penny-web:latest
# Published address of the web container; put your TLS proxy in front of it.
PENNY_BIND=127.0.0.1
PENNY_PORT=8080
EOF
echo "Wrote $target"
