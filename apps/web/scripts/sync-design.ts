// Generates src/design/tokens.css from the design kit's --pk-* tokens (MAZ-83).
// design-kit/src/styles.css is the single source of truth: its light block
// (`:root, .pk-root`) and dark block (`.pk-dark`) become a `:root` block plus a
// `prefers-color-scheme: dark` override, because the web follows the system
// appearance (light and dark only; MAZ-132). Run with --check in CI.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const kitStyles = fileURLToPath(new URL("../../../design-kit/src/styles.css", import.meta.url));
const output = fileURLToPath(new URL("../src/design/tokens.css", import.meta.url));

export function extractBlock(css: string, selector: string): string {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`design-kit styles.css has no "${selector}" block`);
  const open = css.indexOf("{", start);
  const close = css.indexOf("}", open);
  return css.slice(open + 1, close);
}

export function declarations(block: string): [string, string][] {
  const withoutComments = block.replace(/\/\*[\s\S]*?\*\//g, "");
  const result: [string, string][] = [];
  for (const raw of withoutComments.split(";")) {
    const text = raw.trim();
    if (!text) continue;
    const colon = text.indexOf(":");
    const name = text.slice(0, colon).trim();
    if (!name.startsWith("--pk-")) throw new Error(`unexpected declaration in token block: ${text}`);
    result.push([name, text.slice(colon + 1).trim().replace(/\s+/g, " ")]);
  }
  return result;
}

export function renderTokens(css: string): string {
  const light = declarations(extractBlock(css, ":root, .pk-root"));
  const dark = declarations(extractBlock(css, ".pk-dark"));
  const lines = (entries: [string, string][], indent: string) => entries.map(([name, value]) => `${indent}${name}: ${value};`).join("\n");
  return [
    "/* Generated by apps/web/scripts/sync-design.ts from design-kit/src/styles.css. Do not edit. */",
    ":root {",
    "  color-scheme: light dark;",
    lines(light, "  "),
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    "  :root {",
    lines(dark, "    "),
    "  }",
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const expected = renderTokens(readFileSync(kitStyles, "utf8"));
  if (process.argv.includes("--check")) {
    let actual = "";
    try {
      actual = readFileSync(output, "utf8");
    } catch {
      // Missing file is reported below.
    }
    if (actual !== expected) {
      console.error("src/design/tokens.css is out of date with design-kit. Run: npm run design:sync");
      process.exit(1);
    }
    console.log("design tokens are in sync with design-kit");
  } else {
    writeFileSync(output, expected);
    console.log("wrote src/design/tokens.css");
  }
}
