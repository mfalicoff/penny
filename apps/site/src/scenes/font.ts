export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Horizontal advance per character, in font pixels. */
export const ADVANCE = 6;

/**
 * Lit pixels of `text` as [column, row] pairs, row 0 at the top. Throws on a glyph the font
 * doesn't have, so a typo can't silently print blanks.
 */
export function rasterize(text: string): [number, number][] {
  const pixels: [number, number][] = [];
  [...text].forEach((char, index) => {
    const glyph = GLYPHS[char];
    if (!glyph) throw new Error(`No glyph for ${JSON.stringify(char)}`);
    glyph.forEach((row, y) => {
      [...row].forEach((cell, x) => {
        if (cell === "#") pixels.push([index * ADVANCE + x, y]);
      });
    });
  });
  return pixels;
}
